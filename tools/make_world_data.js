#!/usr/bin/env node
/* Generate web/world.json (coastlines and country borders for the Map layout) from Natural Earth data
   packaged as world-atlas.

     npm install world-atlas topojson-client
     node tools/make_world_data.js

   Natural Earth is public domain; world-atlas is ISC (web/vendor/world-atlas.LICENSE). The output holds
   polylines of [longitude, latitude] pairs rounded to one decimal place. */
const fs = require("fs");
const path = require("path");
const topojson = require("topojson-client");

const world = JSON.parse(fs.readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"));
const land = JSON.parse(fs.readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));
const round = (line) => line.map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10]);
// Split lines where they cross the antimeridian, or they would be drawn straight across the whole map.
const split = (lines) => lines.flatMap((line) => {
  const parts = [[line[0]]];
  for (let i = 1; i < line.length; i++) {
    if (Math.abs(line[i][0] - line[i - 1][0]) > 180) parts.push([]);
    parts[parts.length - 1].push(line[i]);
  }
  return parts.filter((part) => part.length > 1);
});

const coast = topojson.mesh(land, land.objects.land);                       // MultiLineString of every ring
const borders = topojson.mesh(world, world.objects.countries, (a, b) => a !== b); // shared borders only
const out = {
  note: "Generated by tools/make_world_data.js from Natural Earth via world-atlas. [lon, lat] polylines.",
  coast: split(coast.coordinates).map(round),
  borders: split(borders.coordinates).map(round),
};
const file = path.join(__dirname, "..", "web", "world.json");
fs.writeFileSync(file, JSON.stringify(out));
console.log(`${out.coast.length} coast lines, ${out.borders.length} border lines, ${fs.statSync(file).size} bytes`);
