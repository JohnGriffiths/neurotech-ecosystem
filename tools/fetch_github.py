#!/usr/bin/env python3
"""Collect GitHub facts about every project repo, for the viewer's "Find a project" feature.

    python tools/fetch_github.py

Needs the GitHub CLI (`gh`) with access to the search API. Writes graph/github.json:

    "mne-tools/mne-python": {"language": "Python", "topics": [...], "stars": 3593, "pushed": "2026-11-12",
                             "open_issues": 625, "license": "BSD-3-Clause", "archived": false,
                             "good_first_issues": 12, "help_wanted": 30, "fetched": "2026-11-14"}

Repos are queried in batches through the search API (several `repo:` qualifiers per query), with pauses to
stay inside its rate limit. Counts of labelled issues use the labels "good first issue" and "help wanted"
and stop at 100 per batch, so a very large number is a lower bound. Repos the search cannot see are left out.
Re-run to refresh; the viewer shows the `fetched` date.
"""
from __future__ import annotations

import datetime
import json
import subprocess
import sys
import time
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ntgraph  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "graph" / "github.json"
BATCH = 6
PAUSE = 7  # seconds between search calls


def search(kind: str, query: str) -> list[dict]:
    time.sleep(PAUSE)
    result = subprocess.run(["gh", "api", "-X", "GET", f"search/{kind}", "-f", f"q={query}", "-f", "per_page=100"],
                            capture_output=True, text=True)
    if result.returncode != 0:
        print(f"  search failed: {result.stderr.strip()[:200]}", file=sys.stderr)
        return []
    return json.loads(result.stdout).get("items", [])


def main() -> int:
    nodes, _, errors, _ = ntgraph.load()
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    repos = sorted({n["repo"] for n in nodes if n.get("repo")})
    today = datetime.date.today().isoformat()
    found: dict[str, dict] = {}
    for i in range(0, len(repos), BATCH):
        group = repos[i:i + BATCH]
        quals = " ".join(f"repo:{r}" for r in group)
        for item in search("repositories", quals):
            found[item["full_name"].lower()] = {
                "language": item.get("language"), "topics": item.get("topics", []), "stars": item["stargazers_count"],
                "pushed": (item.get("pushed_at") or "")[:10], "open_issues": item["open_issues_count"],
                "license": (item.get("license") or {}).get("spdx_id"), "archived": item["archived"],
                "good_first_issues": 0, "help_wanted": 0, "fetched": today,
            }
        for label, key in (("good first issue", "good_first_issues"), ("help wanted", "help_wanted")):
            counts = Counter(it["repository_url"].split("repos/")[-1].lower()
                             for it in search("issues", f'{quals} label:"{label}" state:open is:issue'))
            for repo, n in counts.items():
                if repo in found:
                    found[repo][key] = n
        print(f"{min(i + BATCH, len(repos))}/{len(repos)} repos")

    by_name = {r.lower(): r for r in repos}
    out = {by_name[k]: v for k, v in sorted(found.items()) if k in by_name}
    OUT.write_text(json.dumps({"note": "Generated by tools/fetch_github.py from the GitHub search API.", "repos": out},
                              indent=1, sort_keys=True))
    missing = [r for r in repos if r not in out]
    print(f"{len(out)} of {len(repos)} repos written to {OUT.relative_to(ROOT)}; missing: {missing or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
