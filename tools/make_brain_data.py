#!/usr/bin/env python3
"""Generate the brain reference data used by the viewer's Brain layout.

    pip install nilearn mne scikit-image scipy
    python tools/make_brain_data.py

Writes two committed files (they are not rebuilt in CI; re-run this only to change them):

  web/brain.json         template brain surface (mesh) and head outlines, in MNI mm
  graph/electrodes.json  standard 10-05 electrode sites: scalp position and the cortex point beneath

Sources, both bundled in the pip packages so no download is needed:
  - MNI152 brain mask: nilearn.datasets.load_mni152_brain_mask (ICBM 2009 nonlinear symmetric template)
  - Electrode positions: MNE's `colin27_1005` montage (Colin27 head, close to MNI space)

Electrode scalp positions are taken as MNI mm directly. That is an approximation (Colin27 is not exactly
MNI152) good to roughly 5-10 mm, which is plenty for showing where a headset typically samples. The cortex
point is where a straight line from the scalp site towards the middle of the brain first enters the mask.
"""
from __future__ import annotations

import json
from pathlib import Path

import mne
import numpy as np
from nilearn import datasets
from scipy import ndimage
from scipy.spatial import cKDTree
from skimage import measure

ROOT = Path(__file__).resolve().parent.parent
CENTRE = np.array([0.0, -18.0, 15.0])  # roughly the middle of the brain, MNI mm


def main() -> None:
    img = datasets.load_mni152_brain_mask(resolution=2)
    mask = np.asarray(img.dataobj).astype(float)
    aff = img.affine
    smooth = ndimage.gaussian_filter(mask, 1.0)

    # --- surface mesh (4 mm steps keep it light) ---
    verts, faces, _, _ = measure.marching_cubes(smooth, level=0.5, step_size=2)
    mm = (aff @ np.c_[verts, np.ones(len(verts))].T).T[:, :3]
    # marching_cubes may return vertices that are not all used; keep as is, just round
    mesh = {"v": np.round(mm).astype(int).ravel().tolist(), "f": faces.astype(int).ravel().tolist()}

    # --- dense surface for nearest-point lookups ---
    dverts, _, _, _ = measure.marching_cubes(smooth, level=0.5, step_size=1)
    dense = (aff @ np.c_[dverts, np.ones(len(dverts))].T).T[:, :3]
    tree = cKDTree(dense)

    def inside(p: np.ndarray) -> bool:
        ijk = np.linalg.solve(aff, np.r_[p, 1])[:3]
        i, j, k = np.round(ijk).astype(int)
        if min(i, j, k) < 0 or i >= mask.shape[0] or j >= mask.shape[1] or k >= mask.shape[2]:
            return False
        return smooth[i, j, k] > 0.5

    def cortex_point(scalp: np.ndarray) -> np.ndarray:
        direction = CENTRE - scalp
        direction /= np.linalg.norm(direction)
        for step in np.arange(0, 140, 0.5):
            p = scalp + direction * step
            if inside(p):
                return p
        return dense[tree.query(scalp)[1]]  # ray missed (low sites such as mastoids): nearest surface point

    # --- head outlines: silhouettes of the mask, for the flat view ---
    def outline(axis_drop: int, keep: tuple[int, int]) -> list[list[int]]:
        flat = (mask.max(axis=axis_drop) > 0).astype(float)
        contours = max(measure.find_contours(ndimage.gaussian_filter(flat, 1.0), 0.5), key=len)
        contours = measure.approximate_polygon(contours, tolerance=0.8)
        pts = []
        for a, b in contours:
            idx = [0, 0, 0]
            idx[keep[0]], idx[keep[1]] = a, b
            idx[axis_drop] = mask.shape[axis_drop] // 2
            pts.append([int(round(v)) for v in (aff @ np.r_[idx, 1])[:3]])
        return pts

    axial = [[p[0], p[1]] for p in outline(2, (0, 1))]     # x (right), y (anterior)
    sagittal = [[p[1], p[2]] for p in outline(0, (1, 2))]  # y (anterior), z (superior)
    coronal = [[p[0], p[2]] for p in outline(1, (0, 2))]   # x (right), z (superior)

    out = {
        "note": "Generated by tools/make_brain_data.py from the MNI152 2009 template. MNI mm: x right, y anterior, z superior.",
        "mesh": mesh,
        "outline": {"axial": axial, "sagittal": sagittal, "coronal": coronal},
    }
    (ROOT / "web" / "brain.json").write_text(json.dumps(out, separators=(",", ":")))

    # --- electrodes ---
    montage = mne.channels.make_standard_montage("colin27_1005")
    electrodes = {}
    for name, pos in montage.get_positions()["ch_pos"].items():
        scalp = np.asarray(pos) * 1000.0
        cortex = cortex_point(scalp)
        electrodes[name] = {"scalp": np.round(scalp).astype(int).tolist(), "cortex": np.round(cortex).astype(int).tolist()}
    (ROOT / "graph" / "electrodes.json").write_text(json.dumps(
        {"note": "Generated by tools/make_brain_data.py. MNI mm. `scalp` is the electrode on the head, `cortex` the point on the brain surface beneath it. Approximate (5-10 mm).",
         "electrodes": electrodes}, separators=(",", ":")))

    print(f"mesh: {len(verts)} vertices, {len(faces)} faces; outlines: axial {len(axial)}, sagittal {len(sagittal)}, coronal {len(coronal)} points")
    print(f"electrodes: {len(electrodes)}")
    for k in ("Cz", "Fp1", "Oz", "T7", "C3"):
        print(f"  {k}: scalp {electrodes[k]['scalp']}  cortex {electrodes[k]['cortex']}")


if __name__ == "__main__":
    main()
